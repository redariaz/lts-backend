package com.example.login_service.service;

import com.example.login_service.config.PasswordConfig;
import com.example.login_service.dto.UserDTO;
import com.example.login_service.dto.UserTableDTO;
import com.example.login_service.entity.Login;
import com.example.login_service.entity.Users;
import com.example.login_service.mapper.EntityMapper;
import com.example.login_service.repository.LoginRepository;
import com.example.login_service.repository.UserRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.http.HttpStatus;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;
import reactor.core.publisher.Flux;
import reactor.core.publisher.Mono;

import java.time.LocalDateTime;

@Service
@RequiredArgsConstructor
public class UserService {

    private final UserRepository userRepository;
    private final LoginRepository loginRepository;
    private final PasswordEncoder passwordEncoder;

    @Value("${app.auth.default-password}")
    private String defaultPassword;

    public Flux<Users> getAllUsers() {
        return userRepository.findAll();
    }

    public Mono<Users> createUser(UserDTO userDTO) {
        return userRepository.existsByEmpCode(userDTO.getEmpCode())
                .flatMap(exists -> {
                    if (exists) {
                        return Mono.error(
                                new ResponseStatusException(
                                        HttpStatus.CONFLICT,
                                        "Employee code already exists"
                                )
                        );
                    }
                    return userRepository.existsByUsername(userDTO.getUsername());
                })
                .flatMap(exists -> {
                    if (exists) {
                        return Mono.error(
                                new ResponseStatusException(
                                        HttpStatus.CONFLICT,
                                        "Employee username already exists"
                                )
                        );
                    }
                    return userRepository.existsByEmail(userDTO.getEmail());
                })
                .flatMap(exists -> {
                    if (exists) {
                        return Mono.error(
                                new ResponseStatusException(
                                        HttpStatus.CONFLICT,
                                        "Employee email already exists"
                                )
                        );
                    }
                    Users users = EntityMapper.toUserEntity(userDTO);
                    System.out.println(users + "users");
                    return userRepository.save(users);
                })
                .flatMap(savedUser -> {
                    Login login = new Login();
                    // Use the ID generated by users table
                    login.setUserId(savedUser.getId());
                    // Use the user's email as the login email
                    login.setEmail(savedUser.getEmail());
                    // Never store the plain text password
                    login.setPassword(passwordEncoder.encode(defaultPassword));

                    return loginRepository.save(login)
                            .thenReturn(savedUser);
                });
    }

    public Flux<UserTableDTO> getAllUsersForTable() {
        return userRepository.findAll()
                .map(EntityMapper::toUserDTO);
    }

    public Mono<Users> getUserByEmpCode(Integer empCode) {
        return userRepository.findByEmpCode(empCode)
                .switchIfEmpty(Mono.error(
                        new ResponseStatusException(
                                HttpStatus.NOT_FOUND,
                                "User not found with empCode: " + empCode
                        )
                ));
    }

    public Mono<Users> updateUser(Integer empCode, UserDTO userDTO) {
        if (empCode == null || empCode <= 0) {
            return Mono.error(
                    new ResponseStatusException(
                            HttpStatus.BAD_REQUEST,
                            "Invalid employee code"
                    )
            );
        }
        return userRepository.findByEmpCode(empCode)
                .switchIfEmpty(Mono.error(
                        new ResponseStatusException(
                                HttpStatus.NOT_FOUND,
                                "User not found with employee code: " + empCode
                        )
                ))
                .flatMap(existingUser ->
                            checkDuplicateUsername(userDTO, empCode)
                                    .then(checkDuplicateEmail(userDTO, empCode))
                                    .then(Mono.defer(() -> {
                                        if (userDTO.getFirstName() != null) {
                                            existingUser.setFirstName(userDTO.getFirstName());
                                        }
                                        if (userDTO.getLastName() != null) {
                                            existingUser.setLastName(userDTO.getLastName());
                                        }
                                        if (userDTO.getUsername() != null) {
                                            existingUser.setUsername(userDTO.getUsername());
                                        }
                                        if (userDTO.getEmail() != null) {
                                            existingUser.setEmail(userDTO.getEmail());
                                        }
                                        if (userDTO.getLocationName() != null) {
                                            existingUser.setLocationName(userDTO.getLocationName());
                                        }
                                        if (userDTO.getDeptName() != null) {
                                            existingUser.setDeptName(userDTO.getDeptName());
                                        }
                                        if (userDTO.getRoleName() != null) {
                                            existingUser.setRoleName(userDTO.getRoleName());
                                        }
                                        if (userDTO.getShiftTime() != null) {
                                            existingUser.setShiftTime(userDTO.getShiftTime());
                                        }
                                        if (userDTO.getGender() != null) {
                                            existingUser.setGender(userDTO.getGender());
                                        }
                                        if (userDTO.getDob() != null) {
                                            existingUser.setDob(userDTO.getDob());
                                        }
                                        if (userDTO.getMaritalStatus() != null) {
                                            existingUser.setMaritalStatus(
                                                    userDTO.getMaritalStatus()
                                            );
                                        }
                                        existingUser.setModifiedDate(LocalDateTime.now());
                                        return userRepository.save(existingUser);
                                    }))
                )
                .onErrorMap(DuplicateKeyException.class, ex ->
                        new ResponseStatusException(
                                HttpStatus.CONFLICT,
                                "User with same empCode, username or email already exists"
                        )
                );
    }

    private Mono<Void> checkDuplicateUsername(UserDTO userDTO, Integer empCode) {
        return userRepository.existsByUsernameAndEmpCodeNot(userDTO.getUsername(), empCode)
                .flatMap(exists -> {
                    if (exists) {
                        return Mono.error(
                                new ResponseStatusException(
                                        HttpStatus.CONFLICT,
                                        "Username already exists"
                                )
                        );
                    }
                    return Mono.empty();
                });
    }

    private Mono<Void> checkDuplicateEmail(UserDTO userDTO, Integer empCode) {
        return userRepository.existsByEmailAndEmpCodeNot(userDTO.getEmail(), empCode)
                .flatMap(exists -> {
                    if (exists) {
                        return Mono.error(
                                new ResponseStatusException(
                                        HttpStatus.CONFLICT,
                                        "Email already exists"
                                ));
                    }
                    return Mono.empty();
                });
    }


}
